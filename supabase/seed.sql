-- ---------------------------------------------------------------------------
-- ربط ولي أمر بالأطفال  /  guardian links
-- -----------------------------------------------------------------------------
-- لا يمكن إنشاء مستخدمي المصادقة من ملف seed، لذلك يربط هذا المقطع أوّل
-- حساب "parent" موجود فعلاً (أنشئه عبر /signup) بطفلين للاختبار.
-- ---------------------------------------------------------------------------
do $$
declare
  v_parent uuid;
begin
  select id into v_parent
  from public.profiles
  where role = 'parent'
  order by created_at
  limit 1;

  if v_parent is null then
    raise notice '⚠  لا يوجد حساب ولي أمر. أنشئ حساباً عبر /signup ثم أعد تشغيل هذا الملف.';
  else
    insert into public.guardians (child_id, parent_id, relationship, is_primary) values
      ('b0000000-0000-0000-0000-000000000001', v_parent, 'الأب', true),
      ('b0000000-0000-0000-0000-000000000004', v_parent, 'الأم', true)
    on conflict do nothing;
    raise notice '✓  تم ربط ولي الأمر % بطفلين.', v_parent;
  end if;
end $$;

